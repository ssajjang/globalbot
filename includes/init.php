<?php
/**
 * init.php - 공통 초기화 파일 (관리자 페이지 전용)
 * [정책] 이 파일을 include하는 페이지 = 관리자 페이지 → IP 화이트리스트 체크
 * 센터대시보드/회원대시보드는 init_public.php를 사용 (IP 체크 안 함)
 */

// ============================================================
// 오류 표시 설정
// ============================================================
ini_set('display_errors', 0);         // 화면에 에러 숨김 (보안)
ini_set('log_errors', 1);             // 에러를 로그 파일에 기록
error_reporting(E_ALL);               // 모든 에러 레벨 감지

// ============================================================
// 필수 파일 로드 순서 (순서 변경 금지)
// ============================================================
$base_path = dirname(__DIR__); // global-admin-147 폴더 절대 경로

require_once $base_path . '/config/config.php';   // 1. 전역 설정
require_once $base_path . '/config/database.php'; // 2. DB 연결
require_once $base_path . '/includes/auth_check.php'; // 3. 인증/권한/보안

// ============================================================
// 관리자 페이지 IP 화이트리스트 체크
// [정책] 로그인 페이지는 IP 체크 안 함 (로그인해야 확인 가능)
// ============================================================
$current_file = basename($_SERVER['PHP_SELF']);
$skip_ip_check = ['login.php', 'logout.php']; // IP 체크 제외 페이지

if (!in_array($current_file, $skip_ip_check)) {
    require_admin_ip(); // 화이트리스트에 없는 IP는 즉시 차단
}

// ============================================================
// 현재 페이지 URL 추출 (메뉴 활성화 표시용)
// ============================================================
$current_page = basename($_SERVER['PHP_SELF'], '.php');
